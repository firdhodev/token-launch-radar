import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1260, height: 800 }, deviceScaleFactor: 1 });
const url = new URL('../out/dashboard/index.html', import.meta.url).href;
const shots = fileURLToPath(new URL('../screenshots/', import.meta.url));
mkdirSync(shots, { recursive: true });
await page.goto(url, { waitUntil: 'load' });
await page.waitForSelector('.panel tbody tr');
await page.screenshot({ path: shots + '/1-board.png' });
await page.locator('.panel tbody tr').first().click();
await page.waitForSelector('.detail:not([hidden])');
await page.setViewportSize({ width: 1440, height: 1000 });
await page.screenshot({ path: shots + '/2-detail.png' });
await page.keyboard.press('Escape');
await page.setViewportSize({ width: 1260, height: 800 });
await page.locator('input[type=search]').fill('Ethereum');
await page.waitForTimeout(200);
await page.screenshot({ path: shots + '/3-filtered.png' });
await browser.close();
